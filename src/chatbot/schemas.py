"""Pydantic data schemas for NeuroBot AI Chat API.

Provides robust validation, sanitization, and flexible history parsing.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator

from src.chatbot.config import (
    MAX_HISTORY_MESSAGE_LENGTH,
    MAX_HISTORY_TURNS,
    MAX_MESSAGE_LENGTH,
)


class ChatMessage(BaseModel):
    """A single turn in the conversation history."""
    role: str = Field(..., description="Role of the speaker: 'user', 'model', or 'assistant'")
    content: str = Field(..., description="Text content of the message")

    @model_validator(mode="before")
    @classmethod
    def normalize_message_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Normalize role
            raw_role = str(data.get("role", "user")).lower().strip()
            if raw_role in ["assistant", "bot", "model"]:
                role = "model"
            elif raw_role in ["user", "human"]:
                role = "user"
            else:
                role = "user"

            # Extract content from various possible field names (content, message, text, parts)
            content = ""
            if "content" in data and data["content"] is not None:
                content = str(data["content"]).strip()
            elif "message" in data and data["message"] is not None:
                content = str(data["message"]).strip()
            elif "text" in data and data["text"] is not None:
                content = str(data["text"]).strip()
            elif "parts" in data and isinstance(data["parts"], list):
                # Parts could be a list of strings or dicts
                extracted_parts = []
                for p in data["parts"]:
                    if isinstance(p, str):
                        extracted_parts.append(p)
                    elif isinstance(p, dict) and "text" in p:
                        extracted_parts.append(str(p["text"]))
                content = " ".join(extracted_parts).strip()

            # Enforce max length per history message to prevent token bloat
            if len(content) > MAX_HISTORY_MESSAGE_LENGTH:
                content = content[:MAX_HISTORY_MESSAGE_LENGTH]

            return {"role": role, "content": content}
        return data


class ChatRequest(BaseModel):
    """Payload for POST /api/chat endpoint."""
    message: str = Field(
        ...,
        description="The user's query or message for the medical educational chatbot.",
    )
    history: Optional[List[ChatMessage]] = Field(
        default_factory=list,
        description="Optional list of prior chat turns for multi-turn context.",
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Message cannot be empty or contain only whitespace.")
        v_stripped = v.strip()
        if len(v_stripped) > MAX_MESSAGE_LENGTH:
            raise ValueError(
                f"Message length ({len(v_stripped)} characters) exceeds maximum allowed length of {MAX_MESSAGE_LENGTH} characters."
            )
        return v_stripped

    @field_validator("history")
    @classmethod
    def validate_history(cls, v: Optional[List[ChatMessage]]) -> List[ChatMessage]:
        if not v:
            return []
        # Filter out empty messages
        valid_history = [msg for msg in v if msg.content and msg.content.strip()]
        # Keep only the most recent N turns to prevent token bloat
        if len(valid_history) > (MAX_HISTORY_TURNS * 2):
            valid_history = valid_history[-(MAX_HISTORY_TURNS * 2):]
        return valid_history


class ChatResponse(BaseModel):
    """Successful response format matching PRD specification."""
    success: bool = True
    reply: str = Field(..., description="AI response text generated by Gemini.")
    model: Optional[str] = Field(None, description="The Gemini model utilized.")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC timestamp of the response.",
    )


class ChatStatusResponse(BaseModel):
    """Health/readiness status probe for the Gemini Chatbot service."""
    status: str
    service: str = "NeuroBot AI"
    provider: str = "Google Gemini"
    model: str
    configured: bool
    version: str = "1.0.0"
